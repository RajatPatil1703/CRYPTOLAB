import React, { useState } from 'react';

const STAGES = [
  {
    id: 'key',
    title: '1. Secret Key',
    short: 'UTF-8 Key',
    detail: 'Variable-length secret key (typically 40–2048 bits) provided by the user to seed the internal state.',
  },
  {
    id: 'ksa',
    title: '2. KSA',
    short: 'Key Scheduling',
    detail: 'Key Scheduling Algorithm initializes the 256-byte state array S = [0..255] and permutes it using the secret key.',
  },
  {
    id: 'sbox',
    title: '3. Initial S-Box',
    short: '256-Byte State',
    detail: 'The key-dependent permutation of all 256 possible byte values (0–255) produced by KSA.',
  },
  {
    id: 'prga',
    title: '4. PRGA',
    short: 'Stream Generator',
    detail: 'Pseudo-Random Generation Algorithm continuously swaps elements in S and outputs one keystream byte per iteration.',
  },
  {
    id: 'keystream',
    title: '5. Keystream',
    short: 'K[0..n-1]',
    detail: 'Sequence of pseudorandom bytes generated by PRGA, matching the exact byte length of the input message.',
  },
  {
    id: 'xor',
    title: '6. Bitwise XOR',
    short: 'P ⊕ K',
    detail: 'Each plaintext byte is combined bit-by-bit with its corresponding keystream byte using XOR (reversible with the same keystream).',
  },
  {
    id: 'output',
    title: '7. Ciphertext',
    short: 'Hex Output',
    detail: 'Final encrypted byte sequence encoded in hexadecimal (or recovered UTF-8 plaintext during decryption).',
  },
];

const RC4FlowDiagram = () => {
  const [selectedStage, setSelectedStage] = useState(STAGES[0]);

  return (
    <div className="space-y-3">
      <div className="text-xs font-semibold text-gray-500 dark:text-gray-400 uppercase tracking-wider">
        RC4 Architecture Flow (Click any stage)
      </div>

      <div className="flex flex-wrap items-center gap-1.5">
        {STAGES.map((stage, idx) => {
          const isSelected = selectedStage.id === stage.id;
          return (
            <React.Fragment key={stage.id}>
              <button
                type="button"
                onClick={() => setSelectedStage(stage)}
                className={`px-2.5 py-1.5 rounded-lg border text-left transition-all ${
                  isSelected
                    ? 'bg-green-50 border-green-500 text-green-900 dark:bg-green-900/40 dark:border-green-400 dark:text-green-200 ring-1 ring-green-400/40'
                    : 'bg-gray-50 border-gray-200 text-gray-700 dark:bg-gray-800 dark:border-gray-700 dark:text-gray-300 hover:border-green-400'
                }`}
              >
                <div className="text-[11px] font-bold leading-tight">{stage.title}</div>
                <div className="text-[10px] text-gray-500 dark:text-gray-400 font-mono">
                  {stage.short}
                </div>
              </button>
              {idx < STAGES.length - 1 && (
                <span className="text-gray-400 font-bold text-xs select-none">→</span>
              )}
            </React.Fragment>
          );
        })}
      </div>

      <div className="p-3 rounded-lg bg-gray-50 dark:bg-gray-800/60 border border-gray-200 dark:border-gray-700 text-xs text-gray-700 dark:text-gray-300">
        <span className="font-semibold text-green-700 dark:text-green-400 mr-1.5">
          {selectedStage.title}:
        </span>
        {selectedStage.detail}
      </div>
    </div>
  );
};

export default RC4FlowDiagram;